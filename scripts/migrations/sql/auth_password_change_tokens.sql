CREATE TABLE IF NOT EXISTS auth_password_change_tokens (
    id CHAR(36) NOT NULL,
    id_login VARCHAR(50) COLLATE utf8mb4_unicode_ci NOT NULL,
    destination_email_fingerprint CHAR(64) NOT NULL,
    code_hash CHAR(64) NOT NULL,
    code_fingerprint CHAR(32) NOT NULL,
    pending_password_hash VARCHAR(255) NULL,
    source_password_fingerprint CHAR(64) NOT NULL,
    status ENUM('pending', 'used', 'expired', 'locked', 'revoked') NOT NULL DEFAULT 'pending',
    attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
    max_attempts SMALLINT UNSIGNED NOT NULL,
    issued_at DATETIME NOT NULL,
    expires_at DATETIME NOT NULL,
    used_at DATETIME NULL,
    expired_at DATETIME NULL,
    locked_at DATETIME NULL,
    revoked_at DATETIME NULL,
    requested_ip VARCHAR(64) NULL,
    requested_user_agent VARCHAR(255) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_auth_pwd_change_login_status (id_login, status, issued_at),
    KEY idx_auth_pwd_change_expiration (status, expires_at),
    KEY idx_auth_pwd_change_code_fingerprint (code_fingerprint)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
